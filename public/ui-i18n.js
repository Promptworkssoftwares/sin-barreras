const REVERSE_EN = Object.fromEntries(Object.entries(EN).map(([source, target]) => [target, source]));

let locale = 'es';
let observer;
const originalText = new WeakMap();
const originalAttrs = new WeakMap();

export function getUiLocale() { return locale; }

function storedLocale() {
  try {
    const settings = JSON.parse(localStorage.getItem('sinBarreras.settings.v2') || '{}');
    // Account preference wins over a choice left on this device by another account.
    const preferred = settings.uiLocale || localStorage.getItem(UI_LOCALE_KEY);
    if (UI_LOCALES[preferred]) return preferred;
  } catch { /* use browser language */ }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'es';
}

function variableText(source) {
  const patterns = [
    [/^(\d+) guardadas$/, '$1 saved'],
    [/^(\d+) guardada$/, '$1 saved'],
    [/^(\d+) frase$/, '$1 phrase'],
    [/^(\d+) frases$/, '$1 phrases'],
    [/^(\d+) puntos$/, '$1 points'],
    [/^\+(\d+) puntos$/, '+$1 points'],
    [/^(\d+) palabras listas para repasar$/, '$1 words ready to review'],
    [/^(\d+) palabra lista para repasar$/, '$1 word ready to review'],
    [/^(\d+) imágenes practicadas$/, '$1 images practiced'],
    [/^(\d+\/\d+) imágenes practicadas$/, '$1 images practiced'],
    [/^(\d+(?::\d+)?) practicados hoy$/, '$1 practiced today'],
    [/^(\d+\/\d+) intentos con voz$/, '$1 voice attempts'],
    [/^(\d+\/\d+) bloques de 2 min$/, '$1 two-minute blocks'],
    [/^Bloque de 5 min ✓$/, 'Five-minute block ✓'],
    [/^(\d+) días$/, '$1 days'],
    [/^(\d+) min$/, '$1 min'],
    [/^Bloque guardado: (.+)\. Para que cuente, llega a 2:00\.$/, 'Block saved: $1. Reach 2:00 for it to count.'],
    [/^NIVEL (\d+)$/, 'LEVEL $1'],
    [/^PARTE (\d+)$/, 'PART $1'],
    [/^PARTE (\d+) DE (\d+)$/, 'PART $1 OF $2'],
    [/^Renueva: (.+)$/, 'Resets: $1'],
    [/^Voz: (.+)$/, 'Voice: $1'],
    [/^Voz procesada: (.+) min$/, 'Voice processed: $1 min'],
    [/^Te quedan (.+) min de voz\. El uso general de IA también tiene protección automática\.$/, '$1 voice min remaining. General AI use also has automatic safeguards.'],
    [/^Te quedan (.+) minutos\.$/, '$1 minutes remaining.'],
    [/^Ya utilizaste al menos (.+)% del límite incluido\.$/, 'You have used at least $1% of the included limit.'],
    [/^(.+) de (.+) min de voz$/, '$1 of $2 voice min'],
    [/^(.+) min de voz$/, '$1 voice min'],
    [/^(.+) minutos usados$/, '$1 minutes used'],
    [/^(.+) minutos$/, '$1 minutes'],
    [/^(.+)% usado$/, '$1% used'],
    [/^\+(\d+) puntos · (Muy claro|Vas bien|Sigue practicando)$/, (_, points, feedback) => `+${points} points · ${EN[feedback]}`],
    [/^(.+) · Nivel (\d+)$/, (_, title, level) => `${EN[title] || title} · Level ${level}`],
    [/^(.+) niveles · (.+) sesiones · (.+) palabras · (.+) retos$/, '$1 levels · $2 sessions · $3 words · $4 challenges'],
    [/^(.+) niveles · (.+) sesiones · (.+) palabras$/, '$1 levels · $2 sessions · $3 words'],
    [/^(.+) niveles$/, '$1 levels'],
    [/^(.+) sesiones$/, '$1 sessions'],
    [/^(.+) palabras$/, '$1 words'],
    [/^(.+) retos$/, '$1 challenges']
  ];
  for (const [expression, replacement] of patterns) {
    const match = source.match(expression);
    if (match) return typeof replacement === 'function' ? replacement(...match) : source.replace(expression, replacement);
  }
  return undefined;
}

export function tUi(source) {
  if (typeof source !== 'string' || locale === 'es') return source;
  return EN[source] ?? variableText(source) ?? source;
}

function protectedContent(node) {
  const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
  return Boolean(element?.closest(CONTENT_SELECTOR));
}

function translated(source) {
  return locale === 'en' ? (EN[source] ?? variableText(source) ?? source) : source;
}

function updateTextNode(node, initial = false) {
  const value = node.nodeValue;
  const trimmed = value.trim();
  if (!trimmed) return;
  const known = originalText.get(node);
  const safeLabel = Boolean(node.parentElement?.closest(SAFE_LABEL_SELECTOR));
  if (protectedContent(node) && !initial && !safeLabel) {
    // An initial placeholder is UI copy, but the same node may later contain a
    // transcript or a learner's answer. Never translate that replacement.
    if (!known || (trimmed !== known && trimmed !== EN[known] && trimmed !== variableText(known))) {
      originalText.delete(node);
      return;
    }
  }
  if (known && trimmed !== known && trimmed !== EN[known] && trimmed !== variableText(known)) originalText.delete(node);
  const source = originalText.get(node) || (safeLabel ? (REVERSE_EN[trimmed] || trimmed) : trimmed);
  if (!(source in EN) && variableText(source) === undefined) return;
  originalText.set(node, source);
  const next = translated(source);
  if (next !== trimmed) node.nodeValue = value.replace(trimmed, next);
}

function updateAttributes(element, initial = false) {
  if (protectedContent(element) && !initial && !element.matches(SAFE_LABEL_SELECTOR)) {
    const saved = originalAttrs.get(element);
    if (!saved || !Object.keys(saved).length) return;
  }
  let sources = originalAttrs.get(element);
  if (!sources) { sources = {}; originalAttrs.set(element, sources); }
  for (const attr of TEXT_ATTRS) {
    const current = element.getAttribute(attr);
    if (!current) continue;
    if (sources[attr] && current !== sources[attr] && current !== EN[sources[attr]]) delete sources[attr];
    const source = sources[attr] || (element.matches(SAFE_LABEL_SELECTOR) ? (REVERSE_EN[current] || current) : current);
    if (!(source in EN)) continue;
    sources[attr] = source;
    const next = translated(source);
    if (current !== next) element.setAttribute(attr, next);
  }
}

function translateTree(root, initial = false) {
  if (root.nodeType === Node.TEXT_NODE) { updateTextNode(root, initial); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  updateAttributes(root, initial);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (node.nodeType === Node.TEXT_NODE) updateTextNode(node, initial);
    else updateAttributes(node, initial);
  }
}

function applyLocale() {
  document.documentElement.lang = locale;
  translateTree(document.documentElement);
  for (const select of document.querySelectorAll('[data-ui-locale]')) select.value = locale;
  window.dispatchEvent(new CustomEvent('sinbarreras:ui-locale', { detail: { locale } }));
}

export function setUiLocale(next) {
  if (!UI_LOCALES[next]) return;
  locale = next;
  localStorage.setItem(UI_LOCALE_KEY, next);
  try {
    const key = 'sinBarreras.settings.v2';
    const settings = JSON.parse(localStorage.getItem(key) || '{}');
    localStorage.setItem(key, JSON.stringify({ ...settings, uiLocale: next }));
    window.SinBarrerasCloud?.queueSync?.();
  } catch { /* local UI preference still works */ }
  applyLocale();
}

export function initUiI18n() {
  locale = storedLocale();
  // Capture static copy before rendering modules replace sections with live data.
  translateTree(document.documentElement, true);
  applyLocale();
  document.querySelectorAll('[data-ui-locale]').forEach((select) => {
    select.value = locale;
    select.addEventListener('change', () => setUiLocale(select.value));
  });
  observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') updateTextNode(mutation.target);
      if (mutation.type === 'attributes') updateAttributes(mutation.target);
      for (const added of mutation.addedNodes || []) translateTree(added);
    }
  });
  observer.observe(document.documentElement, {
    subtree: true, childList: true, characterData: true,
    attributes: true, attributeFilter: TEXT_ATTRS
  });
}
